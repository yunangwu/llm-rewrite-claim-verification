"""
Mix-variant rewrite: create a single per-group file by randomly assigning
each dataset item to one of the five variant rewrites.

Usage (via CLI):
    python -m core.run rewrite mix --dataset sciclaimeval --seed 42 [--groups LP FI]

Requires the 5 variant files for each group to already exist (generated by
`rewrite natural`). Validates that all variant files share the same claim_id
order before mixing, then writes one <GROUP>-mix-<seed>.json per group into
the same natural rewrites directory.

Each output item gets an extra ``mix_variant`` field recording which variant
was chosen (e.g. "LP-3"), making the assignment auditable without a sidecar file.
"""

from __future__ import annotations

import random


def create_mix_rewrite(
    variant_items_list: list[list[dict]],
    variants: list[str],
    seed: int,
    group: str,
) -> list[dict]:
    """
    Randomly assign each item to one variant rewrite, using a fixed seed.

    Args:
        variant_items_list: One list[dict] per variant, all must have the same
                            length and identical claim_id order.
        variants:           Variant keys in the same order as variant_items_list
                            (e.g. ["LP-1", "LP-2", "LP-3", "LP-4", "LP-5"]).
                            Used only in error messages and the ``mix_variant`` field.
        seed:               Integer RNG seed; determines the per-item assignment.
        group:              Group name (e.g. "LP"); used only in error messages.

    Returns:
        list[dict] of the same length as each variant file. Each item is a copy
        of the chosen variant's item, with ``mix_variant`` set to the chosen
        variant key.

    Raises:
        ValueError: if variant file lengths differ or claim_id order mismatches.
    """
    if not variant_items_list:
        raise ValueError(f"No variant files provided for group {group!r}.")

    n_items = len(variant_items_list[0])

    # --- length check ---
    for i, items in enumerate(variant_items_list):
        if len(items) != n_items:
            raise ValueError(
                f"Group {group!r}: variant {variants[i]!r} has {len(items)} items "
                f"but {variants[0]!r} has {n_items}. "
                f"Re-generate all variants from the same base dataset."
            )

    # --- claim_id order check ---
    ref_ids = [item.get("claim_id") for item in variant_items_list[0]]
    for i, items in enumerate(variant_items_list[1:], start=1):
        for j, (expected, item_v) in enumerate(zip(ref_ids, items)):
            got = item_v.get("claim_id")
            if expected != got:
                raise ValueError(
                    f"Group {group!r}: claim_id order mismatch at index {j}. "
                    f"{variants[0]!r} has claim_id={expected!r} but "
                    f"{variants[i]!r} has claim_id={got!r}. "
                    f"Re-generate all variants from the same base dataset."
                )

    rng = random.Random(seed)
    n_variants = len(variant_items_list)
    mixed: list[dict] = []
    for i in range(n_items):
        chosen_idx = rng.randrange(n_variants)
        item = dict(variant_items_list[chosen_idx][i])
        item["mix_variant"] = variants[chosen_idx]
        mixed.append(item)

    return mixed
